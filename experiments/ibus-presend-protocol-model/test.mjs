import assert from 'node:assert/strict';
import {Gate,route} from './gate.mjs';
let calls=[]; let enabled=false; let cap=true;
const g=new Gate(()=>enabled ? c=>calls.push(c) : null,()=>{const c=cap;cap=false;return c;});
assert.equal(g.begin(':1','token'),true);
const absent=g.commit(':1',0,'甲');
assert.deepEqual(absent,{state:'no_service',prior_attempts:0});
assert.equal(route(absent,0),'fallback'); assert.deepEqual(calls,[]);
assert.deepEqual(g.commit(':1',0,'甲'),{state:'rejected'});
assert.equal(g.cancel(':1'),true);
cap=true;enabled=true;assert.equal(g.begin(':2','token2'),true);
assert.deepEqual(g.commit(':2',0,'甲'),{state:'attempted'});enabled=false;
const partial=g.commit(':2',1,'乙');assert.deepEqual(partial,{state:'no_service',prior_attempts:1});
assert.equal(route(partial,1),'stop');assert.equal(route(undefined,0),'stop');
assert.equal(route({state:'unknown'},0),'stop');assert.deepEqual(calls,['甲']);
assert.equal(g.cancel(':2'),true);cap=true;
const h=new Gate(()=>()=>{calls.push('attempt');throw Error('after dispatch');},()=>true);
assert.equal(h.begin(':3','token3'),true);assert.deepEqual(h.commit(':3',0,'丙'),{state:'unknown'});
assert.equal(route({state:'unknown'},0),'stop'); assert.deepEqual(h.commit(':3',0,'丙'),{state:'rejected'});
assert.equal(h.cancel(':3'),true);assert.deepEqual(h.commit(':3',1,'丁'),{state:'rejected'});
console.log('6 distinct pre-dispatch and non-replay cases passed');
